export function normalizeSidoLabel(raw: string | null | undefined): string | null {
  if (!raw) return null;
  const s = raw.trim();
  if (!s) return null;
  for (const [prefix, label] of SIDO_PREFIX_LABELS) {
    if (s.startsWith(prefix)) return label;
  }
  return s; // 해외 등 미매칭은 원문 그대로
}
